// Generates js/puzzles.js from engine self-play. Run: node tools/gen-puzzles.js
// A position becomes a puzzle when one move is clearly better than all others.
const fs = require('fs');
const path = require('path');
const M = require('../js/engine.js')();

let seed = 20261111;
const R = () => (seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff;
const rot = b => b.map((_, i) => b[(i + 7) % 14]);
const DEEP = { timeMs: 2500, maxDepth: 14 };

function maxCapture(b, p) {
  let best = 0;
  for (const m of M.legalMoves(b, p)) best = Math.max(best, M.play(b, p, m).captured);
  return best;
}

function classify(b, sol) {
  // Follow the best line while it stays South's turn.
  let cur = b, mv = sol, chain = 0, capture = 0, r;
  for (;;) {
    r = M.play(cur, 0, mv);
    capture += r.captured;
    if (!r.extra) break;
    chain++;
    cur = r.board;
    mv = M.analyze(cur, 0, DEEP).moves[0].move;
  }
  if (chain && capture) return 'combo';
  if (chain) return 'free';
  if (capture) return 'capture';
  const threatBefore = maxCapture(b, 1);
  const threatAfter = r.over ? 0 : maxCapture(r.board, 1);
  if (threatBefore >= 3 && threatAfter < threatBefore) return 'defend';
  return 'quiet';
}

const want = { free: 12, capture: 14, combo: 12, defend: 12, quiet: 10 };
const got = { free: [], capture: [], combo: [], defend: [], quiet: [] };
const seen = new Set();
const total = () => Object.values(got).reduce((a, x) => a + x.length, 0);
const target = Object.values(want).reduce((a, x) => a + x, 0);

for (let g = 0; g < 4000 && total() < target; g++) {
  let b = M.newBoard(), p = 0, over = false, ply = 0;
  while (!over && ply < 60) {
    const lm = M.legalMoves(b, p);
    if (ply >= 6 && lm.length >= 3 && M.sideCount(b, 0) + M.sideCount(b, 1) >= 14 && R() < 0.35) {
      const pb = p === 0 ? b.slice() : rot(b);
      const key = pb.join(',');
      const quick = M.analyze(pb, 0, { timeMs: 1e9, maxDepth: 6, fresh: true });
      if (!seen.has(key) && quick.moves[0].score - quick.moves[1].score >= 10) {
        seen.add(key);
        M.clearTT();
        const a = M.analyze(pb, 0, DEEP);
        const gap = (a.moves[0].score - a.moves[1].score) / M.UNIT;
        // Clear best move, and the game still in the balance.
        if (a.depth >= 10 && gap >= 3 && Math.abs(a.moves[0].score) <= 14 * M.UNIT &&
            pb[6] <= 22 && pb[13] <= 22) {
          const theme = classify(pb, a.moves[0].move);
          if (got[theme].length < want[theme]) {
            got[theme].push({ b: pb, sol: a.moves[0].move, gap: Math.round(gap * 4) / 4, theme });
            process.stderr.write(`${total()}/${target} ${theme}\n`);
          }
        }
      }
    }
    // Mostly sensible play with some noise so positions look like real games.
    let mv;
    if (R() < 0.3) mv = lm[Math.floor(R() * lm.length)];
    else mv = M.analyze(b, p, { timeMs: 1e9, maxDepth: 3 }).moves[0].move;
    const r = M.play(b, p, mv);
    b = r.board; p = r.next; over = r.over; ply++;
  }
}

// Interleave themes from easy to hard so the set ramps up gently.
const order = ['free', 'capture', 'combo', 'defend', 'quiet'];
for (const t of order) got[t].sort((x, y) => y.gap - x.gap);
const out = [], count = total();
for (let round = 0; out.length < count; round++) {
  for (let k = 0; k < order.length; k++) {
    // early rounds favour the simpler themes
    const t = order[k];
    if (round < 3 && k > 2) continue;
    if (got[t].length) out.push(got[t].shift());
  }
}
out.forEach((p, i) => { p.id = 'p' + (i + 1); });
const js = '/* Generated by tools/gen-puzzles.js - do not edit by hand. South (index 0-5) to move. */\n' +
  'window.PUZZLES = [\n' + out.map(p => '  ' + JSON.stringify(p)).join(',\n') + '\n];\n';
fs.writeFileSync(path.join(__dirname, '../js/puzzles.js'), js);
console.log('wrote', out.length, 'puzzles');
